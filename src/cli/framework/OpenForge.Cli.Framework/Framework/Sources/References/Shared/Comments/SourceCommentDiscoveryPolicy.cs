namespace OpenForge.Cli.Core.Framework.Sources.References.Shared.Comments;

internal static class SourceCommentDiscoveryPolicy
{
    internal static readonly IReadOnlyList<string> GeneratedMarkers = ["<auto-generated", "@generated"];

    internal static bool Allows(string text)
    {
        var header = text.AsSpan(0, Math.Min(text.Length, 1024));
        foreach (var marker in GeneratedMarkers)
            if (header.Contains(marker, StringComparison.OrdinalIgnoreCase)) return false;
        return true;
    }
}
