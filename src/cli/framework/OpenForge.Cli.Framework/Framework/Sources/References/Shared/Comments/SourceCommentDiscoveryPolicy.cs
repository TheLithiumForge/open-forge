namespace OpenForge.Cli.Core.Framework.Sources.References.Shared.Comments;

internal static class SourceCommentDiscoveryPolicy
{
    internal const string GeneratedSuffix = ".g.cs";
    internal static readonly IReadOnlySet<string> ExcludedDirectories = new HashSet<string>(StringComparer.OrdinalIgnoreCase)
    {
        ".git", ".open-forge-state", "node_modules", "vendor", "vendors", "generated", "artifacts",
        "bin", "obj", "dist", "build", ".docusaurus", "__snapshots__",
    };

    internal static bool Allows(string path, string text)
    {
        if (path.Split('/').Any(ExcludedDirectories.Contains)
            || path.Contains(".generated.", StringComparison.OrdinalIgnoreCase)
            || path.EndsWith(GeneratedSuffix, StringComparison.OrdinalIgnoreCase)
            || path.Contains(".min.", StringComparison.OrdinalIgnoreCase)) return false;
        var header = text.AsSpan(0, Math.Min(text.Length, 1024));
        return !header.Contains("<auto-generated", StringComparison.OrdinalIgnoreCase)
            && !header.Contains("@generated", StringComparison.OrdinalIgnoreCase);
    }
}
